CREATE TABLE learning_knowledge_progress (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id BIGINT NOT NULL REFERENCES users(id),
  taxonomy_version INTEGER NOT NULL,
  node_code VARCHAR(255) NOT NULL,
  aggregation_rule_version INTEGER NOT NULL,
  mastery_score INTEGER NOT NULL,
  evidence_count INTEGER NOT NULL,
  distinct_session_count INTEGER NOT NULL,
  consecutive_correct_count INTEGER NOT NULL,
  consecutive_incorrect_count INTEGER NOT NULL,
  confidence_score INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL,
  last_practiced_at TIMESTAMP,
  aggregated_at TIMESTAMP NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_learning_knowledge_progress_node
    FOREIGN KEY (taxonomy_version, node_code)
    REFERENCES question_knowledge_nodes(taxonomy_version, code),
  CONSTRAINT uq_learning_knowledge_progress_owner_node
    UNIQUE (owner_user_id, taxonomy_version, node_code),
  CONSTRAINT learning_knowledge_progress_score_check
    CHECK (mastery_score BETWEEN 0 AND 100),
  CONSTRAINT learning_knowledge_progress_confidence_check
    CHECK (confidence_score BETWEEN 0 AND 100),
  CONSTRAINT learning_knowledge_progress_counts_check
    CHECK (evidence_count >= 0 AND distinct_session_count >= 0
      AND consecutive_correct_count >= 0 AND consecutive_incorrect_count >= 0),
  CONSTRAINT learning_knowledge_progress_rule_check
    CHECK (aggregation_rule_version > 0),
  CONSTRAINT learning_knowledge_progress_status_check
    CHECK (status IN ('NOT_STARTED', 'LEARNING', 'MASTERED'))
);

CREATE INDEX idx_learning_knowledge_progress_owner_status
  ON learning_knowledge_progress(owner_user_id, taxonomy_version, status, mastery_score);
