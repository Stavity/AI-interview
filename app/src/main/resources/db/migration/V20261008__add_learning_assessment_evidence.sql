CREATE TABLE learning_assessment_evidence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id BIGINT NOT NULL REFERENCES users(id),
  source_type VARCHAR(32) NOT NULL,
  source_session_id VARCHAR(64) NOT NULL,
  source_answer_id BIGINT NOT NULL,
  source_task_id UUID,
  evaluation_version BIGINT NOT NULL,
  question_index INTEGER NOT NULL,
  taxonomy_version INTEGER NOT NULL,
  node_code VARCHAR(255) NOT NULL,
  tag_role VARCHAR(20) NOT NULL,
  score INTEGER NOT NULL,
  verified BOOLEAN NOT NULL,
  assessed_at TIMESTAMP NOT NULL,
  evaluation_fingerprint VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT learning_evidence_source_type_check
    CHECK (source_type IN ('TEXT_INTERVIEW', 'VOICE_INTERVIEW')),
  CONSTRAINT learning_evidence_tag_role_check
    CHECK (tag_role IN ('PRIMARY', 'SECONDARY')),
  CONSTRAINT learning_evidence_score_check CHECK (score BETWEEN 0 AND 100),
  CONSTRAINT learning_evidence_question_index_check CHECK (question_index >= 0),
  CONSTRAINT fk_learning_evidence_answer_same_owner
    FOREIGN KEY (source_answer_id, owner_user_id)
    REFERENCES interview_answers(id, owner_user_id) ON DELETE CASCADE,
  CONSTRAINT fk_learning_evidence_knowledge_node
    FOREIGN KEY (taxonomy_version, node_code)
    REFERENCES question_knowledge_nodes(taxonomy_version, code),
  CONSTRAINT uk_learning_evidence_idempotency UNIQUE (
    owner_user_id, source_type, source_session_id, question_index,
    node_code, evaluation_fingerprint
  )
);

CREATE UNIQUE INDEX uq_learning_assessment_evidence_id_owner
  ON learning_assessment_evidence(id, owner_user_id);

CREATE INDEX idx_learning_evidence_owner_taxonomy_node_time
  ON learning_assessment_evidence(owner_user_id, taxonomy_version, node_code, assessed_at DESC);

CREATE INDEX idx_learning_evidence_owner_session
  ON learning_assessment_evidence(owner_user_id, source_type, source_session_id);
