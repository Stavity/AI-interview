CREATE TABLE learning_paths (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id BIGINT NOT NULL REFERENCES users(id),
  taxonomy_version INTEGER NOT NULL,
  route_rule_version INTEGER NOT NULL,
  goal TEXT,
  trigger_reason VARCHAR(32) NOT NULL,
  summary VARCHAR(1000) NOT NULL,
  status VARCHAR(20) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  superseded_at TIMESTAMP,
  CONSTRAINT learning_paths_rule_check CHECK (route_rule_version > 0),
  CONSTRAINT learning_paths_status_check CHECK (status IN ('ACTIVE', 'SUPERSEDED'))
);

CREATE UNIQUE INDEX uq_learning_paths_one_active_per_owner
  ON learning_paths(owner_user_id)
  WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX uq_learning_paths_id_owner ON learning_paths(id, owner_user_id);
CREATE INDEX idx_learning_paths_owner_created
  ON learning_paths(owner_user_id, created_at DESC);

CREATE TABLE learning_path_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path_id BIGINT NOT NULL,
  owner_user_id BIGINT NOT NULL,
  taxonomy_version INTEGER NOT NULL,
  node_code VARCHAR(255) NOT NULL,
  sequence_no INTEGER NOT NULL,
  node_name VARCHAR(255) NOT NULL,
  mastery_score INTEGER NOT NULL,
  evidence_count INTEGER NOT NULL,
  difficulty VARCHAR(32) NOT NULL,
  estimated_minutes INTEGER NOT NULL,
  prerequisite BOOLEAN NOT NULL DEFAULT FALSE,
  recommendation_reason VARCHAR(1000) NOT NULL,
  status VARCHAR(20) NOT NULL,
  completed_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_learning_path_items_path_owner
    FOREIGN KEY (path_id, owner_user_id) REFERENCES learning_paths(id, owner_user_id),
  CONSTRAINT fk_learning_path_items_node
    FOREIGN KEY (taxonomy_version, node_code)
    REFERENCES question_knowledge_nodes(taxonomy_version, code),
  CONSTRAINT uq_learning_path_items_sequence UNIQUE (path_id, sequence_no),
  CONSTRAINT learning_path_items_score_check CHECK (mastery_score BETWEEN 0 AND 100),
  CONSTRAINT learning_path_items_evidence_check CHECK (evidence_count >= 0),
  CONSTRAINT learning_path_items_minutes_check CHECK (estimated_minutes > 0),
  CONSTRAINT learning_path_items_status_check CHECK (status IN ('PENDING', 'COMPLETED', 'SKIPPED'))
);

CREATE INDEX idx_learning_path_items_owner_status
  ON learning_path_items(owner_user_id, status, path_id, sequence_no);
