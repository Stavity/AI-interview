ALTER TABLE multi_round_interviews ADD COLUMN orchestration_mode VARCHAR(32) NOT NULL DEFAULT 'STATIC';
ALTER TABLE multi_round_interviews ADD CONSTRAINT multi_round_interviews_mode_check
  CHECK (orchestration_mode IN ('STATIC', 'GOOGLE_ADK', 'STATIC_FALLBACK'));

CREATE TABLE multi_round_workflow_instances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  multi_round_interview_id BIGINT NOT NULL UNIQUE REFERENCES multi_round_interviews(id),
  execution_mode VARCHAR(32) NOT NULL,
  status VARCHAR(16) NOT NULL,
  definition_version VARCHAR(32) NOT NULL,
  definition_json TEXT NOT NULL,
  state_json TEXT NOT NULL,
  checkpoint_key VARCHAR(64) NOT NULL,
  adk_session_id VARCHAR(128),
  lease_until TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT multi_round_workflow_mode_check CHECK (execution_mode IN ('STATIC', 'GOOGLE_ADK', 'STATIC_FALLBACK')),
  CONSTRAINT multi_round_workflow_status_check CHECK (status IN ('READY', 'RUNNING', 'PAUSED', 'COMPLETED', 'FAILED'))
);
CREATE TABLE multi_round_workflow_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_instance_id BIGINT NOT NULL REFERENCES multi_round_workflow_instances(id),
  event_type VARCHAR(48) NOT NULL,
  checkpoint_key VARCHAR(64) NOT NULL,
  payload_json TEXT,
  created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_multi_round_workflow_events_instance ON multi_round_workflow_events(workflow_instance_id, id);

CREATE TABLE multi_round_workflow_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_instance_id BIGINT NOT NULL REFERENCES multi_round_workflow_instances(id),
  checkpoint_key VARCHAR(64) NOT NULL,
  decision_type VARCHAR(48) NOT NULL,
  agent_name VARCHAR(64) NOT NULL,
  policy_version VARCHAR(64) NOT NULL,
  input_hash VARCHAR(64) NOT NULL,
  decision_json TEXT NOT NULL,
  status VARCHAR(16) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  accepted_at TIMESTAMP(6),
  CONSTRAINT multi_round_workflow_decision_status_check CHECK (status IN ('ACCEPTED', 'REJECTED')),
  CONSTRAINT multi_round_workflow_decision_unique UNIQUE(workflow_instance_id, checkpoint_key, decision_type)
);

CREATE TABLE multi_round_final_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  multi_round_interview_id BIGINT NOT NULL UNIQUE REFERENCES multi_round_interviews(id),
  source VARCHAR(32) NOT NULL,
  report_json TEXT NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT multi_round_final_report_source_check CHECK (source IN ('DETERMINISTIC', 'GOOGLE_ADK'))
);
