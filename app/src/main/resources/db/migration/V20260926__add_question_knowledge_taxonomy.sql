CREATE TABLE question_taxonomy_versions (
  version INTEGER PRIMARY KEY,
  status VARCHAR(20) NOT NULL,
  content_hash VARCHAR(64) NOT NULL,
  published_at TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT question_taxonomy_versions_status_check
    CHECK (status IN ('ACTIVE', 'ARCHIVED'))
);

CREATE UNIQUE INDEX uq_question_taxonomy_single_active
  ON question_taxonomy_versions(status)
  WHERE status = 'ACTIVE';

CREATE TABLE question_knowledge_nodes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  taxonomy_version INTEGER NOT NULL REFERENCES question_taxonomy_versions(version),
  code VARCHAR(255) NOT NULL,
  name VARCHAR(255) NOT NULL,
  parent_code VARCHAR(255),
  node_kind VARCHAR(32) NOT NULL,
  description TEXT,
  assignable BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_question_knowledge_node_version_code UNIQUE (taxonomy_version, code),
  CONSTRAINT fk_question_knowledge_node_parent
    FOREIGN KEY (taxonomy_version, parent_code)
    REFERENCES question_knowledge_nodes(taxonomy_version, code),
  CONSTRAINT question_knowledge_nodes_status_check
    CHECK (status IN ('ACTIVE', 'DEPRECATED', 'ARCHIVED'))
);

CREATE INDEX idx_question_knowledge_nodes_parent
  ON question_knowledge_nodes(taxonomy_version, parent_code, status, sort_order);

CREATE TABLE question_knowledge_node_aliases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  taxonomy_version INTEGER NOT NULL,
  node_code VARCHAR(255) NOT NULL,
  alias VARCHAR(255) NOT NULL,
  normalized_alias VARCHAR(255) NOT NULL,
  CONSTRAINT fk_question_knowledge_alias_node
    FOREIGN KEY (taxonomy_version, node_code)
    REFERENCES question_knowledge_nodes(taxonomy_version, code),
  CONSTRAINT uq_question_knowledge_alias UNIQUE (taxonomy_version, node_code, normalized_alias)
);

CREATE INDEX idx_question_knowledge_alias_search
  ON question_knowledge_node_aliases(taxonomy_version, normalized_alias);

CREATE TABLE question_knowledge_node_relations (
  taxonomy_version INTEGER NOT NULL,
  source_code VARCHAR(255) NOT NULL,
  target_code VARCHAR(255) NOT NULL,
  relation_type VARCHAR(32) NOT NULL,
  PRIMARY KEY (taxonomy_version, source_code, target_code, relation_type),
  CONSTRAINT fk_question_knowledge_relation_source
    FOREIGN KEY (taxonomy_version, source_code)
    REFERENCES question_knowledge_nodes(taxonomy_version, code),
  CONSTRAINT fk_question_knowledge_relation_target
    FOREIGN KEY (taxonomy_version, target_code)
    REFERENCES question_knowledge_nodes(taxonomy_version, code),
  CONSTRAINT question_knowledge_relation_type_check
    CHECK (relation_type IN ('RELATED_TO', 'PREREQUISITE_OF', 'SUPERSEDES'))
);

CREATE TABLE question_skill_knowledge_scope (
  taxonomy_version INTEGER NOT NULL,
  skill_id VARCHAR(64) NOT NULL,
  node_code VARCHAR(255) NOT NULL,
  include_descendants BOOLEAN NOT NULL DEFAULT TRUE,
  priority VARCHAR(20) NOT NULL,
  weight NUMERIC(6,3) NOT NULL DEFAULT 1,
  PRIMARY KEY (taxonomy_version, skill_id, node_code),
  CONSTRAINT fk_question_skill_knowledge_scope_node
    FOREIGN KEY (taxonomy_version, node_code)
    REFERENCES question_knowledge_nodes(taxonomy_version, code),
  CONSTRAINT question_skill_knowledge_scope_priority_check
    CHECK (priority IN ('CORE', 'NORMAL', 'OPTIONAL')),
  CONSTRAINT question_skill_knowledge_scope_weight_check CHECK (weight > 0)
);

CREATE INDEX idx_question_skill_knowledge_scope_skill
  ON question_skill_knowledge_scope(taxonomy_version, skill_id, priority);
