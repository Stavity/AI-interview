CREATE TABLE chat_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL,
  is_pinned BOOLEAN NOT NULL DEFAULT FALSE,
  provider_id VARCHAR(64) NOT NULL,
  provider_fingerprint VARCHAR(64) NOT NULL,
  message_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT chat_sessions_status_check CHECK (status IN ('ACTIVE', 'ARCHIVED'))
);

CREATE TABLE chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES chat_sessions(id),
  role VARCHAR(20) NOT NULL,
  content TEXT NOT NULL,
  message_order INTEGER NOT NULL,
  completed BOOLEAN NOT NULL DEFAULT TRUE,
  failure_code VARCHAR(64),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_chat_message_order UNIQUE (session_id, message_order),
  CONSTRAINT chat_messages_role_check CHECK (role IN ('USER', 'ASSISTANT'))
);

CREATE INDEX idx_chat_sessions_pinned_updated ON chat_sessions (is_pinned, updated_at DESC);
CREATE INDEX idx_chat_messages_session_completed_order ON chat_messages (session_id, completed, message_order);
