-- Each model proposal is durable evidence.  A rejected proposal remains auditable;
-- only a policy-gated ACCEPTED decision may change the executable graph.
CREATE TABLE IF NOT EXISTS multi_round_workflow_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_instance_id BIGINT NOT NULL
    REFERENCES multi_round_workflow_instances(id) ON DELETE CASCADE,
  decision_key VARCHAR(160) NOT NULL,
  decision_type VARCHAR(48) NOT NULL,
  agent_name VARCHAR(64) NOT NULL,
  policy_version VARCHAR(64) NOT NULL,
  input_hash VARCHAR(64) NOT NULL,
  status VARCHAR(16) NOT NULL,
  rejection_reason VARCHAR(128),
  decision_json TEXT NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  accepted_at TIMESTAMP(6),
  CONSTRAINT multi_round_workflow_decisions_unique_key UNIQUE(workflow_instance_id, decision_key),
  CONSTRAINT multi_round_workflow_decisions_status_check
    CHECK (status IN ('ACCEPTED', 'REJECTED'))
);

CREATE INDEX IF NOT EXISTS idx_multi_round_workflow_decisions_instance_created
  ON multi_round_workflow_decisions(workflow_instance_id, created_at DESC);
