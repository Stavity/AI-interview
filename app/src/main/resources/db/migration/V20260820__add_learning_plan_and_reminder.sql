CREATE TABLE learning_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  goal TEXT,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL,
  provider_id VARCHAR(64),
  provider_fingerprint VARCHAR(64),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT learning_plans_status_check CHECK (status IN ('DRAFT', 'ACTIVE', 'COMPLETED', 'ARCHIVED')),
  CONSTRAINT learning_plans_date_check CHECK (end_date >= start_date)
);

CREATE TABLE learning_plan_tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id BIGINT NOT NULL REFERENCES learning_plans(id),
  skill_source_id BIGINT REFERENCES learning_skill_sources(id),
  due_date DATE NOT NULL,
  task_type VARCHAR(32) NOT NULL,
  title VARCHAR(255) NOT NULL,
  estimated_minutes INTEGER NOT NULL DEFAULT 30,
  status VARCHAR(20) NOT NULL,
  completed_at TIMESTAMP(6),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT learning_plan_tasks_status_check CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED')),
  CONSTRAINT learning_plan_tasks_minutes_check CHECK (estimated_minutes > 0)
);

CREATE TABLE learning_reminders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES learning_plan_tasks(id),
  remind_at TIMESTAMP(6) NOT NULL,
  channel VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL,
  delivered_at TIMESTAMP(6),
  failure_reason VARCHAR(500),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT learning_reminders_channel_check CHECK (channel IN ('IN_APP', 'BROWSER')),
  CONSTRAINT learning_reminders_status_check CHECK (status IN ('PENDING', 'READY', 'DELIVERED', 'CANCELLED', 'FAILED'))
);

CREATE INDEX idx_learning_plan_tasks_plan_due ON learning_plan_tasks(plan_id, due_date);
CREATE INDEX idx_learning_plan_tasks_due_status ON learning_plan_tasks(due_date, status);
CREATE INDEX idx_learning_reminders_status_time ON learning_reminders(status, remind_at);
