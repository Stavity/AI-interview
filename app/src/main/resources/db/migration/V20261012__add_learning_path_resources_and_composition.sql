ALTER TABLE learning_paths
  ADD COLUMN composition_source VARCHAR(32) NOT NULL DEFAULT 'RULE';

ALTER TABLE learning_paths
  ADD CONSTRAINT learning_paths_composition_source_check
  CHECK (composition_source IN ('RULE', 'AI'));

ALTER TABLE learning_path_items
  ADD CONSTRAINT uq_learning_path_items_id_owner UNIQUE (id, owner_user_id);

CREATE TABLE learning_path_item_resources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path_item_id BIGINT NOT NULL,
  owner_user_id BIGINT NOT NULL REFERENCES users(id),
  skill_source_id BIGINT NOT NULL REFERENCES learning_skill_sources(id),
  source_display_name VARCHAR(255) NOT NULL,
  category_key VARCHAR(64) NOT NULL,
  match_score INTEGER NOT NULL,
  match_reason VARCHAR(500) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_learning_path_item_resources_item_owner
    FOREIGN KEY (path_item_id, owner_user_id)
    REFERENCES learning_path_items(id, owner_user_id),
  CONSTRAINT uq_learning_path_item_resource UNIQUE (path_item_id, skill_source_id),
  CONSTRAINT learning_path_item_resources_score_check CHECK (match_score BETWEEN 1 AND 100)
);

CREATE INDEX idx_learning_path_item_resources_owner_item
  ON learning_path_item_resources(owner_user_id, path_item_id);
