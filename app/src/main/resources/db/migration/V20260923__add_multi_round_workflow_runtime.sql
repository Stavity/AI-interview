-- P1 static workflow runtime.  These changes are additive so existing
-- multi-round interviews can keep their original rounds and be backfilled.

ALTER TABLE multi_round_interviews
  ADD COLUMN IF NOT EXISTS orchestration_mode VARCHAR(32) NOT NULL DEFAULT 'LEGACY_STATIC';

ALTER TABLE multi_round_interviews
  DROP CONSTRAINT IF EXISTS multi_round_interviews_orchestration_mode_check,
  ADD CONSTRAINT multi_round_interviews_orchestration_mode_check
    CHECK (orchestration_mode IN ('LEGACY_STATIC', 'STATIC', 'SHADOW', 'GOOGLE_ADK', 'STATIC_FALLBACK'));

ALTER TABLE multi_rounds
  ADD COLUMN IF NOT EXISTS node_key VARCHAR(64),
  ADD COLUMN IF NOT EXISTS node_type VARCHAR(48),
  ADD COLUMN IF NOT EXISTS display_order INTEGER,
  ADD COLUMN IF NOT EXISTS difficulty_band VARCHAR(32),
  ADD COLUMN IF NOT EXISTS coverage_json TEXT,
  ADD COLUMN IF NOT EXISTS origin VARCHAR(32);

UPDATE multi_rounds
SET node_key = COALESCE(node_key, 'legacy-round-' || id),
    node_type = COALESCE(node_type, round_type),
    display_order = COALESCE(display_order, round_no),
    origin = COALESCE(origin, 'STATIC')
WHERE node_key IS NULL
   OR node_type IS NULL
   OR display_order IS NULL
   OR origin IS NULL;

ALTER TABLE multi_rounds
  ALTER COLUMN node_key SET NOT NULL,
  ALTER COLUMN node_type SET NOT NULL,
  ALTER COLUMN display_order SET NOT NULL,
  ALTER COLUMN origin SET NOT NULL;

ALTER TABLE multi_rounds
  DROP CONSTRAINT IF EXISTS multi_rounds_origin_check,
  ADD CONSTRAINT multi_rounds_origin_check CHECK (origin IN ('STATIC', 'ADK', 'FALLBACK'));

CREATE UNIQUE INDEX IF NOT EXISTS uq_multi_rounds_interview_node_key
  ON multi_rounds(multi_round_interview_id, node_key);
CREATE UNIQUE INDEX IF NOT EXISTS uq_multi_rounds_interview_display_order
  ON multi_rounds(multi_round_interview_id, display_order);

CREATE TABLE IF NOT EXISTS multi_round_workflow_instances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  multi_round_interview_id BIGINT NOT NULL UNIQUE
    REFERENCES multi_round_interviews(id) ON DELETE CASCADE,
  execution_mode VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL,
  definition_version VARCHAR(64) NOT NULL,
  definition_json TEXT NOT NULL,
  state_json TEXT NOT NULL,
  checkpoint_key VARCHAR(96) NOT NULL,
  workflow_revision BIGINT NOT NULL DEFAULT 0,
  lease_until TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT multi_round_workflow_instances_mode_check
    CHECK (execution_mode IN ('LEGACY_STATIC', 'STATIC', 'SHADOW', 'GOOGLE_ADK', 'STATIC_FALLBACK')),
  CONSTRAINT multi_round_workflow_instances_status_check
    CHECK (status IN ('READY', 'RUNNING', 'PAUSED', 'COMPLETED', 'FAILED'))
);

CREATE TABLE IF NOT EXISTS multi_round_workflow_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_instance_id BIGINT NOT NULL
    REFERENCES multi_round_workflow_instances(id) ON DELETE CASCADE,
  event_key VARCHAR(160) NOT NULL,
  event_type VARCHAR(64) NOT NULL,
  checkpoint_key VARCHAR(96) NOT NULL,
  payload_json TEXT,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT multi_round_workflow_events_unique_key UNIQUE(workflow_instance_id, event_key)
);

CREATE INDEX IF NOT EXISTS idx_multi_round_workflow_events_instance_time
  ON multi_round_workflow_events(workflow_instance_id, created_at DESC);
