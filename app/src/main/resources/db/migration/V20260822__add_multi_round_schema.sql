CREATE TABLE multi_round_interviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  interview_session_id BIGINT NOT NULL UNIQUE REFERENCES interview_sessions(id),
  status VARCHAR(32) NOT NULL,
  current_round_no INTEGER NOT NULL DEFAULT 0,
  provider_id VARCHAR(64),
  provider_fingerprint VARCHAR(64),
  started_at TIMESTAMP(6),
  completed_at TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT multi_round_interviews_status_check CHECK (status IN ('CREATED','ROUND_READY','IN_PROGRESS','ROUND_EVALUATING','ROUND_COMPLETED','COMPLETED','FAILED'))
);

CREATE TABLE multi_rounds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  multi_round_interview_id BIGINT NOT NULL REFERENCES multi_round_interviews(id),
  round_no INTEGER NOT NULL,
  round_type VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL,
  question_limit INTEGER NOT NULL,
  started_at TIMESTAMP(6),
  completed_at TIMESTAMP(6),
  report_json TEXT,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT multi_rounds_unique_no UNIQUE(multi_round_interview_id, round_no),
  CONSTRAINT multi_rounds_type_check CHECK (round_type IN ('ALGORITHM','TECHNICAL_1','TECHNICAL_2','HR')),
  CONSTRAINT multi_rounds_status_check CHECK (status IN ('PENDING','IN_PROGRESS','COMPLETED')),
  CONSTRAINT multi_rounds_question_limit_check CHECK (question_limit > 0)
);

CREATE TABLE multi_round_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id BIGINT NOT NULL REFERENCES multi_rounds(id),
  sequence_no INTEGER NOT NULL,
  question_type VARCHAR(32) NOT NULL,
  category_key VARCHAR(128),
  question TEXT NOT NULL,
  reference_answer TEXT,
  answer TEXT,
  status VARCHAR(32) NOT NULL,
  follow_up_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT multi_round_questions_unique_sequence UNIQUE(round_id, sequence_no),
  CONSTRAINT multi_round_questions_status_check CHECK (status IN ('PENDING','ANSWERED','EVALUATED')),
  CONSTRAINT multi_round_questions_follow_up_check CHECK (follow_up_count BETWEEN 0 AND 2)
);

CREATE TABLE algorithm_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id BIGINT NOT NULL REFERENCES multi_round_questions(id),
  language VARCHAR(16) NOT NULL,
  template_version VARCHAR(32) NOT NULL,
  source_code TEXT NOT NULL,
  evaluation_json TEXT,
  score INTEGER,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT algorithm_submissions_language_check CHECK (language IN ('JAVA','PYTHON','CPP'))
);

CREATE INDEX idx_multi_rounds_interview_no ON multi_rounds(multi_round_interview_id, round_no);
CREATE INDEX idx_multi_round_questions_round_sequence ON multi_round_questions(round_id, sequence_no);
CREATE INDEX idx_algorithm_submissions_question ON algorithm_submissions(question_id, created_at DESC);
