CREATE TABLE learning_skill_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skill_id VARCHAR(64) NOT NULL,
  category_key VARCHAR(64) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  description TEXT,
  content_hash VARCHAR(64) NOT NULL,
  status VARCHAR(20) NOT NULL,
  synced_at TIMESTAMP(6) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_learning_skill_source UNIQUE (skill_id, category_key),
  CONSTRAINT learning_skill_sources_status_check
    CHECK (status IN ('ACTIVE', 'UNAVAILABLE'))
);

CREATE INDEX idx_learning_skill_sources_status
  ON learning_skill_sources (status, skill_id);
