CREATE TABLE IF NOT EXISTS multi_round_learning_advice (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  multi_round_interview_id BIGINT NOT NULL UNIQUE
    REFERENCES multi_round_interviews(id) ON DELETE CASCADE,
  source VARCHAR(32) NOT NULL,
  input_hash VARCHAR(64) NOT NULL,
  advice_json TEXT NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT multi_round_learning_advice_source_check CHECK (source IN ('GOOGLE_ADK', 'DETERMINISTIC'))
);
