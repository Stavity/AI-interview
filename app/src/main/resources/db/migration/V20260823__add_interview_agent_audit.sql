CREATE TABLE interview_agent_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  multi_round_interview_id BIGINT NOT NULL REFERENCES multi_round_interviews(id),
  trigger_type VARCHAR(32) NOT NULL,
  status VARCHAR(20) NOT NULL,
  input_hash VARCHAR(64) NOT NULL,
  output_json TEXT,
  error_code VARCHAR(64),
  started_at TIMESTAMP(6) NOT NULL,
  finished_at TIMESTAMP(6),
  CONSTRAINT interview_agent_runs_status_check CHECK (status IN ('RUNNING','SUCCEEDED','REJECTED','FAILED'))
);

CREATE TABLE interview_agent_steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES interview_agent_runs(id),
  step_no INTEGER NOT NULL,
  tool_name VARCHAR(64) NOT NULL,
  input_summary VARCHAR(500),
  output_summary VARCHAR(500),
  duration_ms BIGINT,
  status VARCHAR(20) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT interview_agent_steps_unique_no UNIQUE(run_id, step_no)
);

CREATE INDEX idx_interview_agent_runs_interview_time ON interview_agent_runs(multi_round_interview_id, started_at DESC);
