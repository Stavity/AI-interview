CREATE TABLE learning_progress (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skill_source_id BIGINT NOT NULL,
  mastery_score INTEGER NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL,
  last_practiced_at TIMESTAMP(6),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_learning_progress_source UNIQUE (skill_source_id),
  CONSTRAINT learning_progress_mastery_score_check CHECK (mastery_score BETWEEN 0 AND 100),
  CONSTRAINT learning_progress_status_check CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'MASTERED')),
  CONSTRAINT fk_learning_progress_source FOREIGN KEY (skill_source_id)
    REFERENCES learning_skill_sources(id)
);

CREATE INDEX idx_learning_progress_status_score
  ON learning_progress (status, mastery_score);
