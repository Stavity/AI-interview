CREATE TABLE multi_round_idempotency (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id VARCHAR(36) NOT NULL,
  operation_type VARCHAR(32) NOT NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  multi_round_interview_id BIGINT REFERENCES multi_round_interviews(id),
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT multi_round_idempotency_unique_key UNIQUE(session_id, operation_type, idempotency_key)
);

CREATE INDEX idx_multi_round_idempotency_session_operation ON multi_round_idempotency(session_id, operation_type);
